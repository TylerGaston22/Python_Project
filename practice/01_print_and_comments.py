# 01 - print() and comments
# A comment starts with # and is ignored by the Python interpreter.
# Comments are notes for you, or for other people reading your code.

# print() displays something to the console window
print("I like pizza!")
print("It's really good!")

# Double quotes and single quotes both work for strings
print('Single quotes work too')

# An empty print() prints a blank line
print()

# You can print more than one thing by separating with commas
print("Pizza", "is", "great")
